create table if not exists public.editais (
  id integer generated by default as identity primary key,
  titulo varchar(250) not null,
  instituicao varchar(200) not null,
  link_oficial text,
  prazo date,
  status varchar(30) not null default 'mapeado',
  responsavel_id integer references public.usuarios(id) on delete set null,
  projeto_id integer references public.projetos(id) on delete set null,
  requisitos text,
  observacoes text,
  criado_por integer references public.usuarios(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint editais_status_check check (
    status in ('mapeado', 'em_preparacao', 'submetido', 'aprovado', 'reprovado', 'arquivado')
  ),
  constraint editais_titulo_not_blank check (length(trim(titulo)) > 0),
  constraint editais_instituicao_not_blank check (length(trim(instituicao)) > 0)
);

create index if not exists editais_prazo_status_idx
  on public.editais (prazo, status);

create table if not exists public.edital_checklist (
  id integer generated by default as identity primary key,
  edital_id integer not null references public.editais(id) on delete cascade,
  titulo varchar(250) not null,
  descricao text,
  responsavel_id integer references public.usuarios(id) on delete set null,
  prazo date,
  documento_url text,
  drive_item_id varchar(512),
  concluido boolean not null default false,
  concluido_por integer references public.usuarios(id) on delete set null,
  concluido_em timestamptz,
  criado_por integer references public.usuarios(id) on delete set null,
  criado_em timestamptz not null default now(),
  constraint edital_checklist_titulo_not_blank check (length(trim(titulo)) > 0)
);

create index if not exists edital_checklist_edital_prazo_idx
  on public.edital_checklist (edital_id, concluido, prazo);

create table if not exists public.biblioteca_respostas (
  id integer generated by default as identity primary key,
  titulo varchar(250) not null,
  categoria varchar(120) not null,
  texto text not null,
  versao varchar(60) not null default '1.0',
  aprovado boolean not null default false,
  proprietario_id integer references public.usuarios(id) on delete set null,
  criado_por integer references public.usuarios(id) on delete set null,
  atualizado_por integer references public.usuarios(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint biblioteca_respostas_titulo_not_blank check (length(trim(titulo)) > 0),
  constraint biblioteca_respostas_texto_not_blank check (length(trim(texto)) > 0)
);

create index if not exists biblioteca_respostas_categoria_idx
  on public.biblioteca_respostas (categoria, aprovado, titulo);

create table if not exists public.biblioteca_documentos (
  id integer generated by default as identity primary key,
  drive_item_id varchar(512) not null,
  nome varchar(255) not null,
  web_url text not null,
  categoria varchar(120) not null,
  versao varchar(60) not null default '1.0',
  revisar_em date,
  proprietario_id integer references public.usuarios(id) on delete set null,
  equipe_id integer references public.equipes(id) on delete set null,
  criado_por integer not null references public.usuarios(id),
  vinculo_tipo varchar(30),
  vinculo_id integer,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint biblioteca_documentos_vinculo_tipo_check check (
    vinculo_tipo is null or vinculo_tipo in ('cliente', 'projeto', 'edital', 'tarefa_projeto', 'tarefa_cliente')
  ),
  constraint biblioteca_documentos_vinculo_check check (
    (vinculo_tipo is null and vinculo_id is null)
    or (vinculo_tipo is not null and vinculo_id is not null)
  ),
  constraint biblioteca_documentos_drive_owner_unique unique (drive_item_id, criado_por)
);

-- Garante que se a tabela já existia antes, as novas colunas sejam adicionadas
alter table public.biblioteca_documentos add column if not exists equipe_id integer references public.equipes(id) on delete set null;
alter table public.biblioteca_documentos add column if not exists vinculo_tipo varchar(30);
alter table public.biblioteca_documentos add column if not exists vinculo_id integer;
alter table public.biblioteca_documentos add column if not exists versao varchar(60) not null default '1.0';
alter table public.biblioteca_documentos add column if not exists revisar_em date;
alter table public.biblioteca_documentos add column if not exists proprietario_id integer references public.usuarios(id) on delete set null;

create index if not exists biblioteca_documentos_categoria_idx
  on public.biblioteca_documentos (categoria, nome);
create index if not exists biblioteca_documentos_equipe_idx
  on public.biblioteca_documentos (equipe_id, categoria, nome)
  where equipe_id is not null;
create index if not exists biblioteca_documentos_vinculo_idx
  on public.biblioteca_documentos (vinculo_tipo, vinculo_id)
  where vinculo_tipo is not null;

alter table public.editais enable row level security;
alter table public.edital_checklist enable row level security;
alter table public.biblioteca_respostas enable row level security;
alter table public.biblioteca_documentos enable row level security;
