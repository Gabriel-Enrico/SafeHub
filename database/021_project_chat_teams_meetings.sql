create table if not exists public.projeto_mensagens (
  id bigint generated by default as identity primary key,
  projeto_id integer not null references public.projetos(id) on delete cascade,
  autor_usuario_id integer not null references public.usuarios(id) on delete restrict,
  conteudo varchar(4000) not null check (length(trim(conteudo)) > 0),
  criada_em timestamptz not null default now()
);

create index if not exists projeto_mensagens_projeto_criada_idx
  on public.projeto_mensagens (projeto_id, criada_em desc, id desc);

create table if not exists public.projeto_reunioes (
  id bigint generated by default as identity primary key,
  projeto_id integer not null references public.projetos(id) on delete cascade,
  titulo varchar(255) not null,
  inicio timestamptz not null,
  fim timestamptz not null,
  outlook_event_id varchar(512) not null,
  join_url text not null,
  criado_por integer not null references public.usuarios(id) on delete restrict,
  criado_em timestamptz not null default now(),
  constraint projeto_reunioes_intervalo_valido check (fim > inicio),
  constraint projeto_reunioes_evento_unico unique (criado_por, outlook_event_id)
);

create index if not exists projeto_reunioes_projeto_inicio_idx
  on public.projeto_reunioes (projeto_id, inicio desc);

create or replace function public.usuario_pode_acessar_projeto(p_projeto_id integer)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog
as $$
  select exists (
    select 1
    from public.usuarios u
    join public.projetos p on p.id = p_projeto_id
    where u.auth_user_id = auth.uid()
      and u.ativo = true
      and (
        u.cargo = 'Administrador'
        or u.equipe_id = p.equipe_id
        or exists (
          select 1 from public.projeto_membros pm
          where pm.projeto_id = p.id and pm.usuario_id = u.id
        )
      )
  );
$$;

revoke all on function public.usuario_pode_acessar_projeto(integer) from public, anon;
grant execute on function public.usuario_pode_acessar_projeto(integer) to authenticated;

alter table public.projeto_mensagens enable row level security;
revoke all on table public.projeto_mensagens from anon, authenticated;
grant select on table public.projeto_mensagens to authenticated;
drop policy if exists projeto_mensagens_leitura_membros on public.projeto_mensagens;
create policy projeto_mensagens_leitura_membros
  on public.projeto_mensagens for select to authenticated
  using (public.usuario_pode_acessar_projeto(projeto_id));

alter table public.projeto_reunioes enable row level security;
revoke all on table public.projeto_reunioes from anon, authenticated;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'projeto_mensagens'
     ) then
    alter publication supabase_realtime add table public.projeto_mensagens;
  end if;
end;
$$;
