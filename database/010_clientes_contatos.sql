alter table public.clientes
  add column if not exists pais varchar(120),
  add column if not exists site varchar(500),
  add column if not exists origem_relacionamento varchar(120);

create table if not exists public.contatos_cliente (
  id integer generated by default as identity primary key,
  cliente_id integer not null references public.clientes(id) on delete cascade,
  nome varchar(200) not null,
  cargo varchar(160),
  email varchar(320),
  telefone varchar(60),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  arquivado_em timestamptz,
  constraint contatos_cliente_nome_not_blank check (length(trim(nome)) > 0)
);

create index if not exists contatos_cliente_active_company_idx
  on public.contatos_cliente (cliente_id, nome)
  where arquivado_em is null;

create unique index if not exists contatos_cliente_active_email_unique_idx
  on public.contatos_cliente (cliente_id, lower(btrim(email)))
  where email is not null and btrim(email) <> '' and arquivado_em is null;

create index if not exists clientes_country_idx
  on public.clientes (pais)
  where pais is not null;

alter table public.interacoes
  add column if not exists contato_id integer references public.contatos_cliente(id) on delete set null;

create index if not exists interacoes_contato_timeline_idx
  on public.interacoes (contato_id, data_interacao desc)
  where contato_id is not null;
