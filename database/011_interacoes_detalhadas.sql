-- Apply after 010_clientes_contatos.sql.
-- Extends the existing CRM interaction record for meeting details, participants,
-- follow-up actions, and files, without replacing public.interacoes.
alter table public.interacoes
  add column if not exists titulo varchar(250),
  add column if not exists data_inicio timestamptz,
  add column if not exists data_fim timestamptz,
  add column if not exists status_relacionado varchar(60),
  add column if not exists proxima_acao text;

create table if not exists public.interacao_participantes (
  id integer generated by default as identity primary key,
  interacao_id integer not null references public.interacoes(id) on delete cascade,
  usuario_id integer references public.usuarios(id) on delete set null,
  contato_id integer references public.contatos_cliente(id) on delete set null,
  constraint interacao_participantes_uma_pessoa check (
    (usuario_id is not null and contato_id is null)
    or (usuario_id is null and contato_id is not null)
  )
);

create unique index if not exists interacao_participantes_usuario_unique_idx
  on public.interacao_participantes (interacao_id, usuario_id)
  where usuario_id is not null;
create unique index if not exists interacao_participantes_contato_unique_idx
  on public.interacao_participantes (interacao_id, contato_id)
  where contato_id is not null;

create table if not exists public.cliente_tarefas (
  id integer generated by default as identity primary key,
  cliente_id integer not null references public.clientes(id) on delete cascade,
  interacao_id integer references public.interacoes(id) on delete set null,
  titulo varchar(250) not null,
  descricao text,
  responsavel_id integer references public.usuarios(id) on delete set null,
  prazo date,
  prioridade varchar(20) not null default 'media',
  status varchar(30) not null default 'a_fazer',
  criado_por integer not null references public.usuarios(id),
  criado_em timestamptz not null default now(),
  concluido_em timestamptz,
  constraint cliente_tarefas_titulo_not_blank check (length(trim(titulo)) > 0),
  constraint cliente_tarefas_prioridade_check check (prioridade in ('baixa', 'media', 'alta', 'urgente')),
  constraint cliente_tarefas_status_check check (status in ('a_fazer', 'em_andamento', 'bloqueada', 'em_revisao', 'concluida'))
);

create index if not exists cliente_tarefas_cliente_prazo_idx
  on public.cliente_tarefas (cliente_id, prazo);
create index if not exists cliente_tarefas_interacao_idx
  on public.cliente_tarefas (interacao_id)
  where interacao_id is not null;

alter table public.documentos
  add column if not exists interacao_id integer references public.interacoes(id) on delete set null;
create index if not exists documentos_interacao_idx
  on public.documentos (interacao_id)
  where interacao_id is not null;

alter table public.interacao_participantes enable row level security;
alter table public.cliente_tarefas enable row level security;
