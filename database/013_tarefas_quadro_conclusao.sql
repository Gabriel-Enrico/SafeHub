alter table public.tarefas
  add column if not exists concluido_em timestamptz,
  add column if not exists concluido_por integer references public.usuarios(id) on delete set null;

alter table public.cliente_tarefas
  add column if not exists concluido_por integer references public.usuarios(id) on delete set null;

do $$
declare
  status_attribute smallint;
  constraint_row record;
begin
  select attnum into status_attribute
  from pg_attribute
  where attrelid = 'public.tarefas'::regclass and attname = 'coluna_kanban' and not attisdropped;

  for constraint_row in
    select conname
    from pg_constraint
    where conrelid = 'public.tarefas'::regclass
      and contype = 'c'
      and conkey = array[status_attribute]::smallint[]
      and pg_get_constraintdef(oid) ~* '(a_fazer|em_andamento|concluida)'
  loop
    execute format('alter table public.tarefas drop constraint %I', constraint_row.conname);
  end loop;

  if exists (
    select 1
    from pg_constraint
    where conrelid = 'public.tarefas'::regclass
      and contype = 'c'
      and status_attribute = any(conkey)
      and cardinality(conkey) > 1
  ) then
    raise exception 'A coluna coluna_kanban participa de uma constraint composta; revise-a antes de habilitar novos status.';
  end if;
end $$;

update public.tarefas
set coluna_kanban = case
  when coluna_kanban is null or trim(coluna_kanban) = '' then 'a_fazer'
  when lower(trim(coluna_kanban)) in ('a_fazer', 'a fazer', 'todo', 'to_do') then 'a_fazer'
  when lower(trim(coluna_kanban)) in ('em_andamento', 'em andamento', 'doing', 'in_progress') then 'em_andamento'
  when lower(trim(coluna_kanban)) in ('concluido', 'concluído', 'concluida', 'concluída', 'done') then 'concluida'
  when lower(trim(coluna_kanban)) in ('bloqueada', 'blocked') then 'bloqueada'
  when lower(trim(coluna_kanban)) in ('em_revisao', 'em revisao', 'em revisão', 'review') then 'em_revisao'
  else coluna_kanban
end
where coluna_kanban is distinct from case
  when coluna_kanban is null or trim(coluna_kanban) = '' then 'a_fazer'
  when lower(trim(coluna_kanban)) in ('a_fazer', 'a fazer', 'todo', 'to_do') then 'a_fazer'
  when lower(trim(coluna_kanban)) in ('em_andamento', 'em andamento', 'doing', 'in_progress') then 'em_andamento'
  when lower(trim(coluna_kanban)) in ('concluido', 'concluído', 'concluida', 'concluída', 'done') then 'concluida'
  when lower(trim(coluna_kanban)) in ('bloqueada', 'blocked') then 'bloqueada'
  when lower(trim(coluna_kanban)) in ('em_revisao', 'em revisao', 'em revisão', 'review') then 'em_revisao'
  else coluna_kanban
end;

alter table public.tarefas
  add constraint tarefas_coluna_kanban_quadro_check
  check (coluna_kanban in ('a_fazer', 'em_andamento', 'bloqueada', 'em_revisao', 'concluida')) not valid;

alter table public.tarefas validate constraint tarefas_coluna_kanban_quadro_check;

create table if not exists public.tarefa_historico (
  id integer generated by default as identity primary key,
  origem varchar(20) not null check (origem in ('projeto', 'interacao')),
  tarefa_id integer not null,
  usuario_id integer not null references public.usuarios(id),
  status_anterior varchar(30),
  status_novo varchar(30) not null,
  criado_em timestamptz not null default now()
);

create index if not exists tarefa_historico_task_idx
  on public.tarefa_historico (origem, tarefa_id, criado_em desc);

alter table public.tarefa_historico enable row level security;
