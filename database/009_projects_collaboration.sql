alter table public.projetos
  add column if not exists responsavel_id integer references public.usuarios(id) on delete set null;

create table if not exists public.projeto_membros (
  projeto_id integer not null references public.projetos(id) on delete cascade,
  usuario_id integer not null references public.usuarios(id) on delete cascade,
  adicionado_em timestamptz not null default now(),
  primary key (projeto_id, usuario_id)
);

create table if not exists public.notificacoes (
  id integer generated by default as identity primary key,
  usuario_id integer not null references public.usuarios(id) on delete cascade,
  tipo varchar(40) not null,
  titulo varchar(200) not null,
  mensagem text not null,
  referencia_tipo varchar(40),
  referencia_id integer,
  chave_deduplicacao varchar(200) unique,
  lida_em timestamptz,
  criada_em timestamptz not null default now()
);

create index if not exists notificacoes_usuario_criada_idx
  on public.notificacoes (usuario_id, criada_em desc);
create index if not exists projeto_membros_usuario_idx
  on public.projeto_membros (usuario_id, projeto_id);

alter table public.projeto_membros enable row level security;
alter table public.notificacoes enable row level security;
