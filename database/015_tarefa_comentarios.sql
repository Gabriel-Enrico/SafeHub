create table if not exists public.tarefa_comentarios (
  id integer generated by default as identity primary key,
  projeto_tarefa_id integer references public.tarefas(id) on delete cascade,
  cliente_tarefa_id integer references public.cliente_tarefas(id) on delete cascade,
  usuario_id integer not null references public.usuarios(id),
  comentario text not null,
  criado_em timestamptz not null default now(),
  constraint tarefa_comentarios_uma_origem check (
    (projeto_tarefa_id is not null and cliente_tarefa_id is null)
    or (projeto_tarefa_id is null and cliente_tarefa_id is not null)
  ),
  constraint tarefa_comentarios_not_blank check (length(trim(comentario)) > 0)
);

create index if not exists tarefa_comentarios_projeto_idx
  on public.tarefa_comentarios (projeto_tarefa_id, criado_em, id)
  where projeto_tarefa_id is not null;

create index if not exists tarefa_comentarios_cliente_idx
  on public.tarefa_comentarios (cliente_tarefa_id, criado_em, id)
  where cliente_tarefa_id is not null;

alter table public.tarefa_comentarios enable row level security;
