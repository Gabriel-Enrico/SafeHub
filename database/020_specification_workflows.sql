create table if not exists public.outlook_event_links (
  id bigint generated by default as identity primary key,
  usuario_auth_id uuid not null references auth.users(id) on delete cascade,
  calendar_id text not null,
  event_id text not null,
  vinculo_tipo varchar(30) not null check (
    vinculo_tipo in ('cliente', 'contato', 'interacao', 'projeto', 'tarefa_projeto', 'tarefa_cliente')
  ),
  vinculo_id integer not null,
  criado_por integer references public.usuarios(id) on delete set null,
  criado_em timestamptz not null default now(),
  unique (calendar_id, event_id, vinculo_tipo, vinculo_id)
);
create index if not exists outlook_event_links_entity_idx
  on public.outlook_event_links (vinculo_tipo, vinculo_id);
alter table public.outlook_event_links enable row level security;

create table if not exists public.projeto_marcos (
  id bigint generated by default as identity primary key,
  projeto_id integer not null references public.projetos(id) on delete cascade,
  titulo varchar(200) not null,
  descricao text,
  prazo date,
  status varchar(30) not null default 'pendente'
    check (status in ('pendente', 'em_andamento', 'concluido', 'atrasado')),
  responsavel_id integer references public.usuarios(id) on delete set null,
  criado_por integer references public.usuarios(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  check (length(trim(titulo)) > 0)
);
create index if not exists projeto_marcos_projeto_prazo_idx
  on public.projeto_marcos (projeto_id, prazo, id);
alter table public.projeto_marcos enable row level security;

create table if not exists public.projeto_entregaveis (
  id bigint generated by default as identity primary key,
  projeto_id integer not null references public.projetos(id) on delete cascade,
  titulo varchar(200) not null,
  descricao text,
  prazo date,
  status varchar(30) not null default 'planejado'
    check (status in ('planejado', 'em_andamento', 'entregue')),
  documento_url text,
  responsavel_id integer references public.usuarios(id) on delete set null,
  criado_por integer references public.usuarios(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  check (length(trim(titulo)) > 0)
);
create index if not exists projeto_entregaveis_projeto_idx
  on public.projeto_entregaveis (projeto_id, prazo, id);
alter table public.projeto_entregaveis enable row level security;

alter table public.edital_checklist
  add column if not exists tarefa_projeto_id integer
    references public.tarefas(id) on delete set null;
create index if not exists edital_checklist_tarefa_idx
  on public.edital_checklist (tarefa_projeto_id)
  where tarefa_projeto_id is not null;

create table if not exists public.auditoria_eventos (
  id bigint generated by default as identity primary key,
  usuario_id integer references public.usuarios(id) on delete set null,
  entidade varchar(50) not null,
  entidade_id text not null,
  acao varchar(30) not null,
  alteracoes jsonb not null default '{}'::jsonb,
  criado_em timestamptz not null default now()
);
create index if not exists auditoria_eventos_entidade_idx
  on public.auditoria_eventos (entidade, entidade_id, criado_em desc);
create index if not exists auditoria_eventos_usuario_idx
  on public.auditoria_eventos (usuario_id, criado_em desc);
alter table public.auditoria_eventos enable row level security;

create table if not exists public.usuario_modulo_permissoes (
  usuario_id integer not null references public.usuarios(id) on delete cascade,
  modulo varchar(30) not null check (modulo in ('clientes','tarefas','projetos','oportunidades','agenda','documentos','editais','equipes','usuarios')),
  acao varchar(20) not null check (acao in ('visualizar','gerenciar')),
  permitido boolean not null default false,
  alterado_por integer references public.usuarios(id) on delete set null,
  atualizado_em timestamptz not null default now(),
  primary key (usuario_id, modulo, acao)
);
alter table public.usuario_modulo_permissoes enable row level security;

alter table public.interacoes
  add column if not exists decisoes text;

alter table public.oportunidade_historico
  add column if not exists tipo_evento varchar(30) not null default 'estagio',
  add column if not exists campo varchar(50),
  add column if not exists valor_anterior text,
  add column if not exists valor_novo text;
