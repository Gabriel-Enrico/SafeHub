alter table public.oportunidades
  add column if not exists titulo varchar(200);

update public.oportunidades o
set titulo = c.nome
from public.clientes c
where o.cliente_id = c.id and o.titulo is null;

update public.oportunidades
set estagio = case
  when lower(trim(estagio)) in ('prospeccao', 'prospecção') then 'prospeccao'
  when lower(trim(estagio)) in ('proposta_enviada', 'proposta enviada', 'proposta') then 'proposta_enviada'
  when lower(trim(estagio)) in ('negociacao', 'negociação') then 'negociacao'
  else estagio
end
where estagio is not null;

create table if not exists public.oportunidade_historico (
  id bigint generated by default as identity primary key,
  oportunidade_id integer not null references public.oportunidades(id) on delete cascade,
  estagio_anterior varchar(50),
  estagio_novo varchar(50) not null,
  usuario_id integer not null references public.usuarios(id),
  alterado_em timestamptz not null default now()
);

alter table public.oportunidade_historico enable row level security;

create index if not exists oportunidade_historico_timeline_idx
  on public.oportunidade_historico (oportunidade_id, alterado_em desc, id desc);
